// Writes ARCHITECTURE.md: script load order, and for every function that later files replace
// ("wrap"), the chain of files in the order they apply. Run after adding or reordering files:
//   NODE_PATH=/opt/npm-tools/node_modules node research/architecture/map.cjs
const fs = require('fs'), acorn = require('acorn');
const ROOT = __dirname + '/../../', D = ROOT + 'dist/';
const html = fs.readFileSync(D + 'index.html', 'utf8');
const scripts = [...html.matchAll(/<script src="([^"]+)"/g)].map(m => m[1]);
const styles = [...html.matchAll(/<link rel="stylesheet" href="([^"]+)"/g)].map(m => m[1]).filter(s => !s.startsWith('http'));
const defined = {}, wrapped = {};
const header = f => {
  const m = fs.readFileSync(D + f, 'utf8').match(/^\/\*([\s\S]*?)\*\//);
  return m ? m[1].replace(/^\s*\*?\s?/gm, ' ').replace(/\s+/g, ' ').trim().split('. ')[0].slice(0, 140) : '';
};
for (const f of scripts) {
  if (!fs.existsSync(D + f)) continue;
  const ast = acorn.parse(fs.readFileSync(D + f, 'utf8'), { ecmaVersion: 'latest' });
  for (const node of ast.body) {
    if (node.type === 'FunctionDeclaration') defined[node.id.name] = f;
    if (node.type === 'ExpressionStatement' && node.expression.type === 'AssignmentExpression' && node.expression.left.type === 'Identifier' && /Function/.test(node.expression.right.type))
      (wrapped[node.expression.left.name] = wrapped[node.expression.left.name] || []).push(f);
  }
}
const lines = [
  '# Architecture',
  '',
  'Generated by `research/architecture/map.cjs`. Do not edit by hand.',
  '',
  'The app is plain browser JavaScript with no build step. Every file in `dist/` shares one global scope and loads in the order below. Later files often **wrap** an earlier function: they keep the old one (`const preX = x`) and replace it with a version that calls it and adds behaviour. So **order matters**, and the last wrapper in a chain runs first.',
  '',
  '## Script load order',
  '',
  ...scripts.map((s, i) => `${i + 1}. \`${s}\`${header(s) ? ' — ' + header(s) : ''}`),
  '',
  '## Functions replaced by later files',
  '',
  '| Function | Defined in | Then wrapped by (in order) |',
  '|---|---|---|',
  ...Object.entries(wrapped)
    .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))
    .map(([name, files]) => `| \`${name}\` | ${defined[name] ? '`' + defined[name] + '`' : '–'} | ${files.map(f => '`' + f + '`').join(' → ')} |`),
  '',
  'Also: `learning-checks.js` wraps `answer`, `readingMissionAnswer` and `scienceAnswer` through its `twoTries()` helper (two tries, then show and revisit).',
  '',
  '## Styles (later files win)',
  '',
  ...styles.map((s, i) => `${i + 1}. \`${s}\``),
  '',
  '## Caches',
  '',
  '- `haytham-sharks-vNN` (`sw.js`, bumped every release): the app code, styles, music and backgrounds (about 18 MB).',
  '- `haytham-media-v1`: voice clips and shark photos (about 80 MB). It is kept across releases, filled as items are used and topped up in the background by `media-download.js`.',
  ''
];
fs.writeFileSync(ROOT + 'ARCHITECTURE.md', lines.join('\n'));
console.log('scripts', scripts.length, 'wrapped functions', Object.keys(wrapped).length);
