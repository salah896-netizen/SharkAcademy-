"""Fetch extra quiz photos (key:index ...) to dist/assets/quiz/<key>.webp and write dist/quiz-photos.js credits."""
import json, sys, io, re, os
args = sys.argv[1:]
sys.argv = sys.argv[:1]
exec(open('/home/claude/photos/find.py').read().split("if __name__")[0])
from PIL import Image, ImageOps
D = '/home/claude/shark-academy/dist/assets/quiz/'
os.makedirs(D, exist_ok=True)
cred_path = '/home/claude/photos/quiz-credits.json'
out = json.load(open(cred_path)) if os.path.exists(cred_path) else {}
for a in args:
    key, i = a.split(':'); i = int(i)
    c = json.load(open(f'/home/claude/photos/cand-{key}.json'))[i]
    url = re.sub(r'/(\d+)px-', '/1280px-', c['thumb']) if c['w'] > 1280 else c['url']
    im = Image.open(io.BytesIO(get(url))).convert('RGB')
    im.thumbnail((1280, 1280))
    im = ImageOps.autocontrast(im, cutoff=1, preserve_tone=True)
    im.save(D + key + '.webp', 'WEBP', quality=80)
    out[key] = {'file': 'quiz/' + key + '.webp', 'credit': c['artist'] or 'Wikimedia Commons contributor',
                'page': c['page'], 'license': c['license'], 'title': c['title']}
    print(key, im.size, c['license'])
json.dump(out, open(cred_path, 'w'), indent=1)
open('/home/claude/shark-academy/dist/quiz-photos.js', 'w').write(
    '/* Extra licensed photos for the quizzes (Wikimedia Commons). Generated by research/photos/quizfetch.py. */\n'
    'const quizPhotoData = ' + json.dumps(out, indent=1, ensure_ascii=False) + ';\n')
